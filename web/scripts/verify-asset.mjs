import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve,dirname} from 'node:path';
import {validateBytes} from 'gltf-validator';
import {parseGlb,inspectSkinInfluences} from '../src/gltf-contract.ts';
const input=resolve(process.argv[2]??'public/assets/avatar.glb');
const output=resolve(process.argv[3]??'../reports/gltf-validation.json');
const bytes=new Uint8Array(await readFile(input));
const report=await validateBytes(bytes,{uri:input,maxIssues:2000});
const jsonChunkLength=new DataView(bytes.buffer,bytes.byteOffset).getUint32(12,true);
const gltf=JSON.parse(new TextDecoder().decode(bytes.slice(20,20+jsonChunkLength)));
const config=JSON.parse(await readFile(resolve('public/assets/avatar.web.json'),'utf8'));
const hash=createHash('sha256').update(bytes).digest('hex');
const materials=(gltf.materials??[]).map(m=>m.name);
const nodes=(gltf.nodes??[]).map(n=>n.name);
const morphs=[...new Set((gltf.meshes??[]).flatMap(m=>m.extras?.targetNames??[]))];
const expectedHash=config.modelSha256??config.glbSha256;
const parsedGlb=parseGlb(bytes);
const skinInfluences=inspectSkinInfluences(parsedGlb.gltf,parsedGlb.binary);
const contractIssues=[...skinInfluences.issues];
if(expectedHash&&expectedHash!==hash)contractIssues.push('GLB hash does not match sidecar');
for(const name of config.skinMaterials??[])if(!materials.includes(name))contractIssues.push(`Missing skin material: ${name}`);
for(const name of [config.headNode,...config.hairNodes??[]].filter(Boolean))if(!nodes.includes(name))contractIssues.push(`Missing control node: ${name}`);
for(const names of Object.values(config.morphTargets??{}))for(const name of names)if(!morphs.includes(name))contractIssues.push(`Missing morph target: ${name}`);
const result={checkedAt:new Date().toISOString(),file:input,bytes:bytes.length,sha256:hash,contractIssues,inventory:{skinInfluences,materials,nodes,morphs,meshes:(gltf.meshes??[]).map(m=>m.name),animations:(gltf.animations??[]).map(a=>a.name),extensionsUsed:gltf.extensionsUsed??[],extensionsRequired:gltf.extensionsRequired??[]},validator:report};
await mkdir(dirname(output),{recursive:true});await writeFile(output,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({file:input,bytes:bytes.length,sha256:hash,errors:report.issues.numErrors,warnings:report.issues.numWarnings,infos:report.issues.numInfos,contractIssues,report:output},null,2));
process.exitCode=report.issues.numErrors>0||contractIssues.length>0?1:0;
